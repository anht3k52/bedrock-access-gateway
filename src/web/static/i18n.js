  function normalize(lang) {
    const v = String(lang || "").toLowerCase().slice(0, 2);
    return SUPPORTED.includes(v) ? v : DEFAULT;
  }

  function readStored() {
    try {
      return normalize(localStorage.getItem(STORAGE_KEY));
    } catch {
      return DEFAULT;
    }
  }

  let current = readStored();

  function t(key, vars) {
    const table = M[current] || M[DEFAULT];
    let s = table[key] ?? M.en[key] ?? M[DEFAULT][key] ?? key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        s = s.split(`{${k}}`).join(String(v));
      }
    }
    return s;
  }

  function setLang(lang) {
    current = normalize(lang);
    try {
      localStorage.setItem(STORAGE_KEY, current);
    } catch {
      /* ignore */
    }
    if (typeof document !== "undefined" && document.documentElement) {
      document.documentElement.lang =
        current === "zh" ? "zh-CN" : current === "vi" ? "vi" : current;
    }
    return current;
  }

  function getLang() {
    return current;
  }

  function localeTag() {
    return LOCALES[current] || LOCALES[DEFAULT];
  }

  // Apply default (Chinese) on first load
  setLang(current);

  window.MrdevI18n = {
    SUPPORTED,
    DEFAULT,
    LABELS,
    t,
    setLang,
    getLang,
    localeTag,
  };
